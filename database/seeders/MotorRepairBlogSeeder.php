        $portfolioId = DB::table('portfolios')
            ->where('slug', 'case-repair-vacuum-3-motors-carwash')
            ->value('id');

        $payload = $this->blogPayload($shop, $phone, $line, $portfolioId ? (int) $portfolioId : null, $publishedAt);
        $slug = $payload['slug'];

        $existingId = DB::table('blogs')->where('slug', $slug)->value('id');

        if ($existingId) {
            DB::table('blogs')->where('id', $existingId)->update(array_merge($payload, [
                'updated_at' => $now,
            ]));
            $blogId = (int) $existingId;
        } else {
            $blogId = (int) DB::table('blogs')->insertGetId(array_merge($payload, [
                'created_at' => $now,
                'updated_at' => $now,
            ]));
        }

        if ($portfolioId) {
            DB::table('portfolios')->where('id', $portfolioId)->update([
                'related_blog_id' => $blogId,
                'updated_at' => $now,
            ]);
        }
    }

