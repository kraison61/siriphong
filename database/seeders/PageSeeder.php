                'sort_order' => 1,
                'is_published' => true,
                'content_updated_at' => $now,
            ])
        );

        $children = [
            ['slug' => 'car-care', 'data' => $this->carCare(), 'order' => 1],
            ['slug' => 'burnt-motor', 'data' => $this->motorBurn(), 'order' => 2],
        ];

        foreach ($children as $child) {
            Page::query()->updateOrCreate(
                ['slug' => $child['slug']],
                array_merge($child['data'], [
                    'slug' => $child['slug'],
                    'parent_id' => $hub->id,
                    'sort_order' => $child['order'],
                    'is_published' => true,
                    'content_updated_at' => $now,
                ])
            );
        }

        $roots = [
            ['data' => $this->pricing(), 'order' => 2],
            ['data' => $this->portfolio(), 'order' => 3],
            ['data' => $this->aboutUs(), 'order' => 4],
            ['data' => $this->contactUs(), 'order' => 5],
        ];

        foreach ($roots as $root) {
            Page::query()->updateOrCreate(
                ['slug' => $root['data']['slug']],
                array_merge($root['data'], [
                    'parent_id' => null,
                    'sort_order' => $root['order'],
                    'is_published' => true,
                    'content_updated_at' => $now,
                ])
